// Рекурсивна функція лічильник
// Виводить num в консоль і викликає себе з num - 1
// Зупиняється коли num стає менше або рівне 0
function countdown(num) {
  // Базовий випадок: зупиняємо рекурсію
  if (num <= 0) return;
 
  console.log(num); // виводимо поточне значення
 
  countdown(num - 1); // рекурсивний виклик з меншим значенням
}
 
// Запускаємо лічильник з числа 5
countdown(5);