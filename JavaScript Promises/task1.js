// Завдання 1
// Функція приймає 2 аргументи:
//   text довільний текст
//   ms кількість мілісекунд
// Через вказану кількість мілісекунд функція виводить текст у консоль.
 
function printWithDelay(text, ms) {
  setTimeout(() => {
    console.log(text);
  }, ms);
}
 
// Приклад використання:
printWithDelay("Цей текст з'явиться через 2 секунди", 2000);
printWithDelay("А цей одразу (0 мс)", 0);